"""Builds src/word_dict.inc, the two static dictionaries of the Tier 2 word filter.

    python3 make_dict.py PROSE_TRAINING CODE_TRAINING > ../../src/word_dict.inc

Each dictionary holds the 16,192 words (64 one-byte codes + 63 * 256 two-byte
codes) with the largest estimated saving, count * (length - 1), counted
case-insensitively. Prose words are [a-z]+; code words are identifiers
[a-z_][a-z0-9_]*. Only words of 2..254 characters are kept, so every entry
satisfies the filter's format rules (see word_filter.hpp).

The shipped file was trained on text that is not part of the benchmark corpus:
prose on five Project Gutenberg books (ids 1342, 2701, 98, 1661, 84), code on
20 MB of Python from third-party packages (pip, pygments, poetry, setuptools,
mypy, ...). Only word frequencies are used; no text is copied.
"""
import collections
import re
import sys

KEEP = 64 + 63 * 256


def build(path, code):
    text = open(path, 'rb').read()
    pat = re.compile(rb'[A-Za-z_][A-Za-z0-9_]*' if code else rb'[A-Za-z]+')
    cnt = collections.Counter(w.lower() for w in pat.findall(text) if 2 <= len(w) < 255)
    words = sorted(cnt, key=lambda w: (-cnt[w] * (len(w) - 1), w))[:KEEP]
    return [w.decode() for w in words]


def emit(name, words):
    print(f'constexpr const char* {name}[] = {{')
    for i in range(0, len(words), 8):
        print('    ' + ', '.join(f'"{w}"' for w in words[i:i + 8]) + ',')
    print('};')


print('// Generated by tools/word_dict/make_dict.py; do not edit.')
emit('kProseWords', build(sys.argv[1], False))
emit('kCodeWords', build(sys.argv[2], True))
